    def test_actual_editor_assembles_fresh_fixture_and_preserves_existing_output(self):
        edit = self.load('live_edit_assembly_test', '05-film/edit.py')
        import numpy as np
        source = self.media()
        destination = self.root / 'new-edit'
        self.task['delivery'] = str(destination / 'Evie-Follow-the-Warm-LTX.mp4')
        for relative in ('produce.py', '02-blocking/shots.py', '02-blocking/prompts.py', '03-audio/cast_lines.py'):
            path = self.root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text('Synthetic source declaration')
            self.task['production']['inputs'].append(a.reference(path))
        self.task['production']['inputs'].append(a.reference(edit.__file__))
        save(self.root / '03-audio/lines-v2.json', [])
        self.update()
        audio = self.root / 'audio'
        (audio / 'song-a').mkdir(parents=True)
        (audio / 'song-a/audio.flac').write_text('Synthetic audio input; read is supplied by fixture')
        (audio / 'music_stem.py').write_text('Synthetic audio implementation fixture')
        stem = types.ModuleType('music_stem')
        tone = .1 * np.sin(2 * np.pi * 440 * np.arange(96000) / 48000)
        stem.read = lambda path: np.stack([tone, tone], axis=1).astype(np.float32)
        stem.smooth = lambda n: np.linspace(0, 1, n)
        args = ['ltx', '--destination', str(destination), '--expected', self.token]
        with patch.object(edit, 'units', ['A', 'B', 'C']), patch.object(edit, 'total', 3), \
             patch.object(edit, 'starts', {'S05': .5, 'A': 0, 'B': 1, 'C': 2}), patch.object(edit, 'OLD_AUDIO', audio), \
             patch.object(edit, 'LINES', {}), patch.object(edit, 'effects', return_value=np.zeros((144000, 2), np.float32)), \
             patch.object(edit.produce, 'seconds', return_value=1), \
             patch.object(edit.produce, 'results', return_value={f'ltx-{u}-t1': str(source) for u in ('A', 'B', 'C')}), \
             patch.object(edit.os, 'chdir'), patch.dict(sys.modules, {'music_stem': stem}):
            self.assertEqual(edit.main(args), 0)
            candidate = j.read_json(destination / 'candidate.json')
            self.assertEqual(a.cut_frames(candidate), [24, 48])
            self.assertIn('INCOMPLETE', candidate['label'])
            before = a.reference(self.task['delivery'])
            with self.assertRaisesRegex(ValueError, 'fresh edit'):
                edit.main(args)
            self.assertEqual(a.reference(self.task['delivery']), before)

