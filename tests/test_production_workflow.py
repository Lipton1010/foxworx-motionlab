def save(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(j.canonical(value))


class WorkflowTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        (self.root / 'production').mkdir()
        self.authority = self.root / 'decisions.md'
        self.authority.write_text('SYNTHETIC: current assignment for integration tests only')
        self.brief = self.root / 'brief.md'
        self.brief.write_text('SYNTHETIC connected action; no real film approval')
        self.artifact = self.root / 'review.mp4'
        self.artifact.write_text('Not a video: gate tests inject reviewer judgments honestly labeled synthetic')
        self.task = dict(task='fixture', revision='r1', goal='Test production boundaries',
                         profile='narrative-film', authority=a.reference(self.authority),
                         decisions=[dict(decision='Synthetic test', source=str(self.authority))],
                         superseded=[], unresolved=[], next_action='Test', delivery=str(self.artifact),
                         rejected_artifacts=[], exceptions=[], reuse=[], requirements=a.film_requirements(),
                         production=dict(inputs=[a.reference(self.brief)], pilot_jobs={}, repair_limits={'escape': 2}))
        self.token = a.record(self.root / 'production/task', self.task, 'new')
        self.timeline = dict(fps=24, frames=72, shots=[
            dict(id=f'S{i}', start=i-1, end=i) for i in range(1, 4)])
        save(self.root / 'timeline.json', self.timeline)
        self.note = self.root / 'synthetic-review.txt'
        self.note.write_text('Synthetic declarations; no listening, playback or semantic verification performed')
        self.prepare = Mock(side_effect=self.prepared)
        self.output = self.root / 'generated.mp4'
        self.output.write_text('Synthetic generated bytes')
        self.state = dict(status='completed', current=True, result={'outputs': [{'path': str(self.output)}]})

    def prepared(self, name, kind, settings, *, dependencies):
        path = self.root / 'jobs' / name / 'revision'
        path.mkdir(parents=True)
        return path

    def update(self):
        self.token = a.record(self.root / 'production/task', self.task, self.token)

    def item(self, name='take1', seed=1):
        return dict(name=name, kind='image', settings=dict(seed=seed))

    def plan(self, items, name='plan.json'):
        path = self.root / name
        save(path, items)
        return path

    def pilot(self, items):
        self.task['production']['pilot_jobs'] = {x['name']: a.fingerprint(x) for x in items}
        self.update()

    def candidate_review(self, purpose='pilot'):
        _, _, deps = w.context(self.root, self.token)
        candidate = dict(task_sha256=self.token, purpose=purpose, label='synthetic',
                         artifact=a.reference(self.artifact), timeline=a.reference(self.root / 'timeline.json'),
                         dependencies=[a.reference(p) for p in deps])
        row = dict(status='passed', method='Synthetic judgment injection', finding='Assumed pass for boundary test',
                   evidence=[a.reference(self.note)])
        checks = {key: dict(row, inspected=rule['modalities']) for key, rule in self.task['requirements'].items()}
        for frame in (24, 48):
            checks[f'cut:{frame}'] = dict(row, inspected=['frame-pair', 'motion', 'audio'], frames=[frame-1, frame],
                                         staging='Synthetic continuous action', before=a.reference(self.note), after=a.reference(self.note))
        review = dict(task_sha256=self.token, candidate_sha256=a.fingerprint(candidate),
                      artifact_sha256=candidate['artifact']['sha256'], reviewer='Synthetic fixture', checks=checks)
        return candidate, review

    def permit_scale(self):
        candidate, review = self.candidate_review()
        save(self.root / 'production/pilot-candidate.json', candidate)
        save(self.root / 'production/pilot-review.json', review)
        return candidate, review

    def batch(self, plan, **kwargs):
        with patch.object(j, 'status', return_value=self.state), patch.object(j, 'run', return_value=self.state):
            return w.run_batch(self.root, plan, self.prepare, expected=self.token, **kwargs)

    def test_missing_pilot_blocks_even_one_scale_job_before_preparation(self):
        with self.assertRaises((OSError, ValueError)):
            self.batch(self.plan([self.item()]))
        self.prepare.assert_not_called()

    def test_failed_pilot_retained_despite_later_passing_declaration(self):
        c, r = self.permit_scale()
        r['checks']['story']['status'] = 'failed'
        save(self.root / 'production/pilot-review.json', r)
        plan = self.plan([self.item()])
        with self.assertRaisesRegex(ValueError, 'story'):
            self.batch(plan)
        r['checks']['story']['status'] = 'passed'
        save(self.root / 'production/pilot-review.json', r)
        with self.assertRaisesRegex(ValueError, 'story'):
            self.batch(plan)
        self.prepare.assert_not_called()

    def test_missing_listening_blocks_scale_despite_claimed_pass(self):
        c, r = self.permit_scale()
        r['checks']['motion_audio']['inspected'] = ['motion', 'asr']
        save(self.root / 'production/pilot-review.json', r)
        with self.assertRaisesRegex(ValueError, 'motion_audio'):
            self.batch(self.plan([self.item()]))
        self.prepare.assert_not_called()

    def test_pilot_scope_is_exact_settings_not_job_count(self):
        self.pilot([self.item()])
        with self.assertRaisesRegex(ValueError, 'bounded pilot'):
            self.batch(self.plan([self.item(seed=2)]), phase='pilot')
        self.prepare.assert_not_called()

    def test_pending_and_unknown_stop_batch_preserve_results_and_resume_same_revision(self):
        items = [self.item(), self.item('take2')]
        self.pilot(items)
        plan = self.plan(items)
        selected = self.root / 'plans/results.json'
        save(selected, {'accepted_old_take': 'keep.mp4'})
        for status in ('pending', 'unknown_submission'):
            with self.subTest(status=status):
                self.state = dict(status=status, current=True)
                result = self.batch(plan, phase='pilot')
                self.assertEqual(result['status'], status)
                self.assertEqual(j.read_json(selected), {'accepted_old_take': 'keep.mp4'})
                self.assertEqual(self.prepare.call_count, 1)
        self.state = dict(status='completed', current=True, result={'outputs': [{'path': str(self.output)}]})
        result = self.batch(plan, phase='pilot')
        self.assertFalse(result['completion'])
        self.assertEqual(self.prepare.call_count, 2)
        self.assertEqual(j.read_json(selected)['accepted_old_take'], 'keep.mp4')

    def test_repair_budget_persists_across_plans_seeds_and_task_revisions(self):
        self.permit_scale()
        for n in (1, 2):
            self.batch(self.plan([self.item(f'fix{n}', n)], f'fix{n}.json'), phase='repair', defect='escape')
        self.task['revision'] = 'r2'
        self.update()
        self.permit_scale()
        with self.assertRaisesRegex(ValueError, 'budget exhausted'):
            self.batch(self.plan([self.item('fix3', 3)]), phase='repair', defect='escape')
        self.assertEqual(self.prepare.call_count, 2)

    def test_changed_task_or_dependency_cannot_start_generation(self):
        self.pilot([self.item()])
        old = self.token
        self.task['revision'] = 'r2'
        self.update()
        with self.assertRaisesRegex(ValueError, 'Stale task'):
            w.run_batch(self.root, self.plan([self.item()]), self.prepare, expected=old, phase='pilot')
        self.brief.write_text('Changed required action')
        with self.assertRaises(ValueError):
            self.batch(self.plan([self.item()]), phase='pilot')
        self.prepare.assert_not_called()

    def test_task_change_during_run_cannot_publish_result_selection(self):
        self.pilot([self.item()])
        def run(*args, **kwargs):
            self.task['revision'] = 'new instruction'
            self.update()
            return self.state
        with patch.object(j, 'status', return_value=self.state), patch.object(j, 'run', side_effect=run):
            with self.assertRaisesRegex(ValueError, 'Stale task'):
                w.run_batch(self.root, self.plan([self.item()]), self.prepare, expected=self.token, phase='pilot')
        self.assertFalse((self.root / 'plans/results.json').exists())

    def test_historical_take_is_not_silently_prepared_again(self):
        self.pilot([self.item()])
        save(self.root / 'jobs/take1/selected-revision.json', 'historical-revision')
        with self.assertRaisesRegex(ValueError, 'Historical take'):
            self.batch(self.plan([self.item()]), phase='pilot')
        self.prepare.assert_not_called()

    def test_delivery_requires_current_context_exact_bytes_and_review(self):
        candidate, review = self.candidate_review('final')
        c, r = self.root / 'candidate.json', self.root / 'review.json'
        save(c, candidate)
        save(r, review)
        receipt = w.deliver(self.root, self.token, c, r)
        self.assertTrue(receipt['result']['completion'])
        self.artifact.write_text('Different film with same name')
        with self.assertRaises(ValueError):
            w.deliver(self.root, self.token, c, r)

    def test_omitting_shared_context_is_not_an_approval_bypass(self):
        candidate, review = self.candidate_review('final')
        candidate['dependencies'] = []
        review['candidate_sha256'] = a.fingerprint(candidate)
        with self.assertRaisesRegex(ValueError, 'production context'):
            w.gate(self.root, self.token, 'deliver', candidate, review)

    def test_profile_extensions_cannot_be_dropped_from_live_task(self):
        del self.task['requirements']['blocking']
        with self.assertRaisesRegex(ValueError, 'blocking'):
            self.update()

    def media(self):
        path = self.root / 'source.mp4'
        subprocess.run(['ffmpeg', '-v', 'error', '-f', 'lavfi', '-i', 'color=red:s=32x32:r=24:d=1',
                        '-f', 'lavfi', '-i', 'anullsrc=r=48000:cl=stereo', '-t', '1',
                        '-c:v', 'libx264', '-c:a', 'aac', str(path)], check=True)
        return path

    def edit_inputs(self, end=24):
        source = self.media()
        timeline = dict(fps=24, frames=24, shots=[dict(id='S1', start=0, end=1)])
        sources = [dict(path=str(source), in_frame=0, out_frame_exclusive=end)]
        return timeline, sources

    def test_short_source_and_existing_destination_rejected_before_encoding(self):
        timeline, sources = self.edit_inputs()
        sources[0]['out_frame_exclusive'] = 48
        timeline.update(frames=48, shots=[dict(id='S1', start=0, end=2)])
        with self.assertRaisesRegex(ValueError, 'too short'):
            w.begin_edit(self.root, self.root / 'edit', self.token, timeline, sources, [])
        self.assertFalse((self.root / 'edit').exists())
        (self.root / 'edit').mkdir()
        with self.assertRaisesRegex(ValueError, 'fresh edit'):
            w.begin_edit(self.root, self.root / 'edit', self.token, timeline, sources, [])

    def test_real_decode_creates_only_unapproved_candidate_and_detects_source_change(self):
        timeline, sources = self.edit_inputs()
        destination = self.root / 'edit'
        inputs = w.begin_edit(self.root, destination, self.token, timeline, sources, [])
        master = destination / 'master.mp4'
        master.write_bytes(Path(sources[0]['path']).read_bytes())
        candidate = w.finish_edit(self.root, master, self.token, inputs, {'frames': 24, 'fps': 24, 'audio_rate': 48000})
        self.assertIn('INCOMPLETE', candidate['label'])
        self.assertFalse((self.root / 'production/deliveries').exists())
        Path(sources[0]['path']).write_bytes(b'changed')
        with self.assertRaises(ValueError):
            w.finish_edit(self.root, master, self.token, inputs, {'frames': 24})


